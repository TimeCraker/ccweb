import { expect, test } from '@playwright/test'
test.use({ baseURL:'http://127.0.0.1:3495',viewport:{width:1440,height:960} })
test.beforeEach(async({page})=>{await page.addInitScript(()=>{localStorage.setItem('ccweb.locale','zh');localStorage.setItem('ccweb.theme','system')})})
test('V2 reference workbench, brand and integrated composer at four widths',async({page},info)=>{
 await page.goto('/')
 await expect(page.getByLabel('运行模式',{exact:true})).toBeEnabled()
 await expect(page.locator('.sidebar-brand img')).toHaveAttribute('src','/brand/timecraker-mark-v1.svg')
 expect(await page.locator('link[rel=icon]').getAttribute('href')).toContain('timecraker-favicon')
 for(const width of [1280,1440,1920,2560]){
  await page.setViewportSize({width,height:960})
  for(const colorScheme of ['dark','light'] as const){
   await page.emulateMedia({colorScheme})
   await expect(page.locator('.composer-card')).toBeInViewport()
   const card=await page.locator('.composer-card').boundingBox(),mode=await page.getByLabel('运行模式',{exact:true}).boundingBox()
   expect(card&&mode&&mode.y>=card.y&&mode.y+mode.height<=card.y+card.height).toBe(true)
   expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
   await page.screenshot({path:info.outputPath(`empty-${colorScheme}-${width}.png`),animations:'disabled'})
  }
 }
})
