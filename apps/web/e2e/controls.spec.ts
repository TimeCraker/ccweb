test('native handoff preserves completed task status and GUI resumes explicitly', async ({ page }) => {
  const states: string[] = []
  page.on('websocket', (ws) =>
    ws.on('framereceived', ({ payload }) => {
      try {
        const message = JSON.parse(String(payload))
        if (message.t === 'state') states.push(message.state)
      } catch {
        /* Non-JSON is not a protocol state. */
      }
    }),
  )
  await page.goto('/')
  await expect(page.getByRole('button', { name: '工作方式', exact: true })).toBeEnabled()
  const input = page.getByRole('textbox', { name: '任务输入', exact: true })
  await input.fill('【E2E】 before native handoff')
  await input.press('Enter')
  await expect(page.getByText('【E2E】模拟完成：【E2E】 before native handoff', { exact: true })).toBeVisible()
  await openNativeTerminal(page)
  await page.getByLabel('原生操作').selectOption('help')
  await page.getByRole('button', { name: '启动原生操作' }).click()
  await expect(page.getByRole('status').filter({ hasText: '进程已退出' })).toBeVisible({ timeout: 20000 })
  expect(states).toContain('native_handoff')
  expect(states).not.toContain('cancelled')
  await page.getByRole('button', { name: '结束进程' }).click()
  await page.getByRole('button', { name: '返回对话', exact: true }).click()
  await input.fill('【E2E】 after native handoff')
  await input.press('Enter')
  await expect(page.getByText('【E2E】模拟完成：【E2E】 after native handoff', { exact: true })).toBeVisible()
})

test('native authentication changes future defaults without relabeling the active session', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('button', { name: '工作方式', exact: true })).toBeEnabled()
  await page.getByRole('textbox', { name: '任务输入', exact: true }).fill('【E2E】 auth source snapshot')
  await page.getByRole('textbox', { name: '任务输入', exact: true }).press('Enter')
  await expect(page.getByText('【E2E】模拟完成：【E2E】 auth source snapshot', { exact: true })).toBeVisible()
  await page.keyboard.press('Control+,')
  const dialog = page.getByRole('dialog', { name: '设置', exact: true })
  await dialog.getByRole('tab', { name: '模型与连接', exact: true }).click()
  await page.getByLabel('认证来源').selectOption('native')
  await expect(page.getByLabel('认证来源')).toHaveValue('native')
  await expect(dialog.getByText(/当前会话：/)).toBeVisible()
  await dialog.getByRole('button', { name: '关闭设置' }).click()
  await page.reload()
  await page.keyboard.press('Control+,')
  await expect(page.getByLabel('认证来源')).toHaveValue('native')
  await page.getByLabel('认证来源').selectOption('inherit')
  await expect(page.getByLabel('认证来源')).toHaveValue('inherit')
})
