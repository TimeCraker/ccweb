  await page.getByRole('menuitem', { name: /运行详情/ }).click()
  const drawer = page.getByRole('complementary', { name: '运行详情' })
  await expect(drawer).toBeVisible()
  await drawer.getByRole('tab', { name: '任务与回退', exact: true }).click()
  await drawer.getByLabel('文件检查点').selectOption({ index: 1 })
