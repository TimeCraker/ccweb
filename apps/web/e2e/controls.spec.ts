import { test, expect } from '@playwright/test'
test.use({ baseURL: 'http://127.0.0.1:3495' })
test('GUI commands select the right settings and runtime controls (simulated SDK)', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('ccweb.locale', 'zh'))
  await page.goto('/')
  await expect(page.getByLabel('运行模式', { exact: true })).toBeEnabled()
  const input = page.getByRole('textbox', { name: '任务输入', exact: true })
  await input.fill('/permissions'); await input.press('Control+Enter')
  await expect(page.getByRole('tab', { name: '运行与权限', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: '关闭设置' }).click()
  await input.fill('【E2E】 controls task'); await input.press('Control+Enter')
  await expect(page.getByText('【E2E】模拟完成：【E2E】 controls task', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '运行详情', exact: true }).click()
  await page.getByRole('button', { name: '任务与回退', exact: true }).click()
  await page.getByLabel('文件检查点').selectOption({ index: 1 })
  await page.getByRole('button', { name: '预览文件回退' }).click()
  await expect(page.getByText('fixture-file.ts', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '关闭运行详情' }).click()
  await page.getByRole('button', { name: 'settings', exact: true }).click()
  await page.getByRole('tab', { name: '模型与连接', exact: true }).click()
  await page.getByRole('button', { name: '发现原生模型（已启动会话）' }).click()
  await page.getByRole('button', { name: '关闭设置' }).click()
  await expect(page.getByLabel('模型', { exact: true }).locator('option').filter({ hasText: 'fixture-discovered' })).toHaveCount(1)
})

test('new resource drafts are protected and settings restores focus', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('ccweb.locale', 'zh'))
  await page.goto('/')
  const button = page.getByRole('button', { name: 'settings', exact: true })
  await button.click()
  await page.getByRole('tab', { name: 'Skills', exact: true }).click()
  await page.getByRole('button', { name: '新建Skills', exact: true }).click()
  const name = page.locator('.resource-create').getByLabel('名称')
  await name.fill('e2e-unsaved')
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('tab', { name: 'Commands', exact: true }).click()
  await expect(name).toHaveValue('e2e-unsaved')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '关闭设置' }).click()
  await expect(button).toBeFocused()
})
