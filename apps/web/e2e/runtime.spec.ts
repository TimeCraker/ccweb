import { expect, test, type Page } from '@playwright/test'
test.use({ baseURL: 'http://127.0.0.1:3495' })
test.beforeEach(async ({ page }) => { await page.addInitScript(() => localStorage.setItem('ccweb.locale', 'zh')) })
async function ready(page: Page) { await page.goto('/'); await expect(page.getByText(/^(已连接|Connected)$/)).toBeVisible(); await expect(page.getByLabel('运行模式',{exact:true})).toBeEnabled() }
async function send(page: Page, text: string) { await page.getByRole('textbox', { name: '任务输入', exact: true }).fill(text); await page.getByRole('textbox', { name: '任务输入', exact: true }).press('Control+Enter') }
async function completed(page: Page, text: string) { await expect(page.getByText(`【E2E】模拟完成：${text}`, { exact: true })).toBeVisible() }
test('approval survives reload, preserves draft and stays isolated from another client', async ({ page, browser }, info) => {
  await ready(page)
  await send(page, 'APPROVAL reconnect')
  await expect(page.locator('.permission-dock')).toBeVisible()
  await page.getByRole('textbox', { name: '任务输入', exact: true }).fill('【E2E】保留草稿')
  const other = await browser.newContext()
  const otherPage = await other.newPage(); await ready(otherPage)
  await expect(otherPage.locator('.permission-dock')).toHaveCount(0)
  await page.reload()
  await expect(page.locator('.permission-dock')).toBeVisible()
  await expect(page.getByRole('textbox', { name: '任务输入', exact: true })).toHaveValue('【E2E】保留草稿')
  await expect(page.getByRole('button', {name:'停止生成',exact:true})).toBeVisible()
  await page.screenshot({ path: info.outputPath('approval.png') })
  await page.getByRole('button', { name: '允许', exact: true }).click()
  await completed(page, 'APPROVAL reconnect')
  await expect(page.locator('.permission-dock')).toHaveCount(0)
  await page.getByRole('button',{name:'改动与检查',exact:true}).click()
  await expect(page.getByRole('heading',{name:/fixture.txt/})).toBeVisible()
  await page.getByRole('button',{name:'返回对话',exact:true}).click()
  await expect(otherPage.getByText('【E2E】模拟完成：APPROVAL reconnect')).toHaveCount(0)
  await expect(page.getByLabel('运行指标')).toContainText('tok/s')
  await other.close()
})
