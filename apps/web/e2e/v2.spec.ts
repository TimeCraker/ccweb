import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('ccweb.locale', 'zh'))
})

test('configuration CRUD, shared source draft, cancel and source scopes through UI', async ({ page }, info) => {
  page.on('dialog', (dialog) => void dialog.accept())
  await page.goto('/')
  await expect(page.getByText(/^(已连接|Connected)$/)).toBeVisible()
  await page.keyboard.press('Control+,')
  const dialog = page.getByRole('dialog', { name: '设置', exact: true })
  await dialog.getByRole('tab', { name: '技能', exact: true }).click()
  const name = `e2e-review-${Date.now().toString(36)}`
  await dialog.getByRole('button', { name: '新建', exact: true }).click()
  await page.locator('.resource-create').getByLabel('名称').fill(name)
  await page.getByRole('button', { name: '创建', exact: true }).click()
  await expect(page.locator('.editor-head h4')).toContainText(name)
  await page.getByLabel('说明', { exact: true }).fill('')
  await page.getByLabel('说明', { exact: true }).pressSequentially('【E2E】 shared draft description')
  await expect(page.getByLabel('说明', { exact: true })).toBeFocused()
  await page.getByRole('button', { name: '源码', exact: true }).click()
  const source = page.getByRole('textbox', { name: '配置源码', exact: true })
  await expect(source).toHaveValue(/shared draft description/)
  await source.fill((await source.inputValue()).replace('---\n\n#', 'custom: preserve\n---\n\n#'))
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await page.getByRole('button', { name: '确认保存', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已保存' })).toBeVisible()
  await expect(page.locator('.editor-head h4')).toBeInViewport()
  await page.screenshot({ path: info.outputPath('skill-editor.png'), animations: 'disabled' })
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByLabel('说明', { exact: true }).fill('discarded')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.getByLabel('说明', { exact: true })).toHaveValue('【E2E】 shared draft description')
  await page.getByRole('button', { name: '复制', exact: true }).click()
  await page.locator('.resource-create').getByLabel('名称').fill(`${name}-copy`)
  await page.getByRole('button', { name: '创建', exact: true }).click()
  await expect(page.locator('.editor-head h4')).toContainText(`${name}-copy`)
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.locator('.editor-head h4')).toHaveCount(0)
  await page.locator('.resource-list button').filter({ has: page.getByText(name, { exact: true }) }).click()
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await dialog.getByRole('tab', { name: '指令', exact: true }).click()
  await page.getByRole('button', { name: '新建', exact: true }).click()
  await page.locator('.resource-create').getByLabel('名称').fill(`e2e:${name}`)
  await page.getByRole('button', { name: '创建', exact: true }).click()
  await expect(page.locator('.editor-head h4')).toContainText(`e2e:${name}`)
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.locator('.editor-head h4')).toHaveCount(0)
})

test('conversation-first layouts keep the composer and drawers inside the viewport', async ({ page }, testInfo) => {
  for (const width of [1280, 1440, 1920]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await expect(page.getByRole('textbox', { name: '任务输入', exact: true })).toBeVisible()
    await expect(page.locator('.composer')).toBeInViewport()
    await expect(page.locator('.runtime-details')).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: '更多', exact: true }).click()
    await page.getByRole('menuitem', { name: /运行详情/ }).click()
    await expect(page.getByRole('complementary', { name: '运行详情' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: '关闭面板' }).click()
    await page.keyboard.press('Control+,')
    await expect(page.getByRole('dialog', { name: '设置', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`settings-${width}.png`) })
    await page.getByRole('button', { name: '关闭设置', exact: true }).click()
  }
  await page.setViewportSize({ width: 1440, height: 960 })
  for (const colorScheme of ['dark', 'light'] as const) {
    await page.emulateMedia({ colorScheme })
    await page.screenshot({ path: testInfo.outputPath(`workbench-${colorScheme}.png`), animations: 'disabled' })
  }
  for (const zoom of [1.25, 1.5]) {
    await page.evaluate((value) => {
      document.documentElement.style.zoom = String(value)
    }, zoom)
    await expect(page.locator('.composer')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2)).toBe(true)
  }
  await page.evaluate(() => {
    document.documentElement.style.zoom = ''
  })
})

test('typing keeps focus and unsaved connection requires explicit discard', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.sidebar-footer-row')).toContainText(/已连接|Connected/)
  await page.keyboard.press('Control+,')
  const dialog = page.getByRole('dialog', { name: '设置', exact: true })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '添加连接' }).click()
  const name = page.getByLabel('连接名称', { exact: true })
  await name.pressSequentially('audit-draft')
  await expect(name).toBeFocused()
  page.once('dialog', (prompt) => void prompt.dismiss())
  await dialog.getByRole('button', { name: '关闭设置', exact: true }).click()
  await expect(name).toHaveValue('audit-draft')
  page.once('dialog', (prompt) => void prompt.accept())
  await dialog.getByRole('button', { name: '关闭设置', exact: true }).click()
  await expect(dialog).toHaveCount(0)
})
