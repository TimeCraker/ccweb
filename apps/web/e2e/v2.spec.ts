import { expect, test } from '@playwright/test'
test('configuration CRUD, shared source draft, cancel and source scopes through UI', async ({ page }, info) => {
  page.on('dialog', dialog => void dialog.accept())
  await page.goto('/')
  await expect(page.getByText(/^(已连接|Connected)$/)).toBeVisible()
  await page.getByRole('button', { name: 'settings', exact: true }).click()
  await page.getByRole('tab', { name: 'Skills', exact: true }).click()
  const name = `e2e-review-${Date.now().toString(36)}`
  await page.getByRole('button', { name: '新建Skills', exact: true }).click()
  await page.locator('.resource-create').getByLabel('名称').fill(name)
  await page.getByRole('button', { name: '创建', exact: true }).click()
  await expect(page.locator('.resource-heading h3')).toHaveText(name)
  await page.getByLabel('说明', { exact: true }).fill('【E2E】 shared draft description')
  await page.getByRole('button', { name: '源码', exact: true }).click()
  const source = page.getByRole('textbox', { name: '配置源码', exact: true })
  await expect(source).toHaveValue(/shared draft description/)
  await source.fill((await source.inputValue()).replace('---\n\n#', 'custom: preserve\n---\n\n#'))
  await page.getByRole('button', { name: '保存更改', exact: true }).click()
  await page.getByRole('button', { name: '确认保存', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已保存' })).toBeVisible()
  await expect(page.locator('.resource-heading h3')).toBeInViewport()
  await page.screenshot({ path: info.outputPath('skill-editor.png'), animations: 'disabled' })
  await page.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByLabel('说明', { exact: true }).fill('discarded')
  await page.getByRole('button', { name: '取消更改', exact: true }).click()
  await expect(page.getByLabel('说明', { exact: true })).toHaveValue('【E2E】 shared draft description')
  await page.getByRole('button', { name: '复制', exact: true }).click()
  await page.locator('.resource-create').getByLabel('名称').fill(`${name}-copy`)
  await page.getByRole('button', { name: '创建', exact: true }).click()
  await expect(page.locator('.resource-heading h3')).toHaveText(`${name}-copy`)
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await expect(page.locator('.resource-heading h3')).toHaveCount(0)
  await page.getByRole('button', { name: `${name} 当前项目`, exact: true }).click()
  await page.getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('tab', { name: 'Commands', exact: true }).click()
  await page.getByRole('button', { name: '新建Commands', exact: true }).click()
  await page.locator('.resource-create').getByLabel('名称').fill(`e2e:${name}`)
  await page.getByRole('button', { name: '创建', exact: true }).click()
  await expect(page.locator('.resource-heading h3')).toHaveText(`e2e:${name}`)
  await page.getByRole('button', { name: '删除', exact: true }).click()
})
test('conversation-first layouts and persistent metrics at desktop sizes', async ({ page }, testInfo) => {
  for (const width of [1280, 1440, 1920]) {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await expect(page.getByRole('textbox', { name: '任务输入', exact: true })).toBeVisible()
    await expect(page.getByLabel('运行指标')).toBeVisible()
    await expect(page.locator('.runtime-details')).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('button', { name: '运行详情', exact: true }).click()
    await expect(page.getByRole('button', { name: '关闭运行详情' })).toBeVisible()
    await page.getByRole('button', { name: '关闭运行详情' }).click()
    await page.getByRole('button', { name: 'settings', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`settings-${width}.png`) })
    await page.getByRole('button', { name: '关闭设置', exact: true }).click()
  }
  await page.setViewportSize({ width: 1440, height: 960 })
  for (const colorScheme of ['dark', 'light'] as const) {
    await page.emulateMedia({ colorScheme })
    await page.screenshot({ path: testInfo.outputPath(`workbench-${colorScheme}.png`), animations: 'disabled' })
  }
  for (const zoom of [1.25, 1.5]) {
    await page.evaluate(value => { document.documentElement.style.zoom = String(value) }, zoom)
    await expect(page.getByLabel('运行指标')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.evaluate(() => { document.documentElement.style.zoom = '' })

})
